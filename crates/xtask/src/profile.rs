use crate::views::VIEWS_DIR;
use std::path::{Path, PathBuf};
use std::process::{Command, Output};

pub const TOP: usize = 25;
pub const HOT_PATH: &str = "hot-path.md";

#[derive(Debug, PartialEq, Eq)]
pub struct Hotspot {
    pub overhead: String,
    pub dso: String,
    pub symbol: String,
}

fn run(command: &mut Command) -> Result<String, String> {
    let output: Output = command
        .output()
        .map_err(|e| format!("cannot run {command:?}: {e}"))?;
    if !output.status.success() {
        return Err(format!(
            "{command:?} failed: {}",
            String::from_utf8_lossy(&output.stderr).trim()
        ));
    }
    Ok(String::from_utf8_lossy(&output.stdout).into_owned())
}

pub fn profile(root: &Path, pid: u32, seconds: u32) -> Result<PathBuf, String> {
    let scratch: PathBuf = root.join("target/xtask");
    std::fs::create_dir_all(&scratch).map_err(|e| format!("{}: {e}", scratch.display()))?;
    let data: PathBuf = scratch.join("perf.data");
    let cmdline: String = std::fs::read_to_string(format!("/proc/{pid}/cmdline"))
        .map_err(|e| {
            format!("process {pid} is not visible here ({e}); a cargo runner with its own PID namespace hides host processes, so run target/debug/xtask directly")
        })?
        .split('\0')
        .filter(|a| !a.is_empty())
        .collect::<Vec<&str>>()
        .join(" ");
    let started: String = run(Command::new("date").args(["-u", "+%Y-%m-%dT%H:%M:%SZ"]))?;
    run(Command::new("perf")
        .args(["record", "-q", "-g", "-e", "task-clock", "-o"])
        .arg(&data)
        .args(["-p", &pid.to_string(), "--", "sleep", &seconds.to_string()]))?;
    let report: String = run(Command::new("perf")
        .args([
            "report",
            "--stdio",
            "--no-children",
            "--fields",
            "overhead,dso,sym",
            "--field-separator",
            "\t",
            "-g",
            "none",
            "-i",
        ])
        .arg(&data))?;
    let hot: Vec<Hotspot> = hotspots(&report);
    if hot.is_empty() {
        return Err(format!("perf recorded no samples for pid {pid}"));
    }
    let markdown: String = render(
        started.trim(),
        pid,
        &cmdline,
        seconds,
        &samples(&report),
        &hot,
    );
    let dir: PathBuf = root.join(VIEWS_DIR);
    std::fs::create_dir_all(&dir).map_err(|e| format!("{}: {e}", dir.display()))?;
    let out: PathBuf = dir.join(HOT_PATH);
    std::fs::write(&out, markdown).map_err(|e| format!("{}: {e}", out.display()))?;
    Ok(out)
}

pub fn samples(report: &str) -> String {
    report
        .lines()
        .find_map(|l| l.strip_prefix("# Samples: "))
        .map(|s| s.split(" of ").next().unwrap_or(s).trim().to_string())
        .unwrap_or_else(|| String::from("unknown"))
}

pub fn hotspots(report: &str) -> Vec<Hotspot> {
    report
        .lines()
        .filter(|l| !l.starts_with('#'))
        .filter_map(|l| {
            let mut fields: std::str::Split<char> = l.split('\t');
            let overhead: &str = fields.next().map(str::trim).filter(|f| f.ends_with('%'))?;
            let dso: &str = fields.next()?.trim();
            let symbol: &str = fields.next()?.trim();
            Some(Hotspot {
                overhead: overhead.to_string(),
                dso: dso.to_string(),
                symbol: symbol.to_string(),
            })
        })
        .take(TOP)
        .collect()
}

fn cell(text: &str) -> String {
    text.replace('|', "\\|")
}

pub fn render(
    started: &str,
    pid: u32,
    cmdline: &str,
    seconds: u32,
    samples: &str,
    hotspots: &[Hotspot],
) -> String {
    let mut out: String = format!(
        "# Hot path\n\nGenerated by `cargo xtask profile` at {started} from `perf record -g -e task-clock` on pid {pid} (`{}`) for {seconds} s, {samples} samples. Self time, top {TOP} symbols.\n\n| Self | DSO | Symbol |\n|---:|---|---|\n",
        cell(cmdline)
    );
    for h in hotspots {
        out.push_str(&format!(
            "| {} | {} | `{}` |\n",
            h.overhead,
            cell(&h.dso),
            cell(&h.symbol)
        ));
    }
    out
}

#[cfg(test)]
mod tests {
    use super::{Hotspot, hotspots, render, samples};

    const REPORT: &str = "# Total Lost Samples: 0\n#\n# Samples: 159  of event 'task-clock:u'\n# Event count (approx.): 39750000\n#\n# Overhead\tShared Object\tSymbol                \n 42.77% \tlibc.so.6    \t[.] splice\n 35.22% \tyes          \t[.] drop_in_place<Vec<u8> >\n\n";

    #[test]
    fn an_empty_report_has_no_hotspots() {
        assert_eq!(hotspots(""), vec![]);
    }

    #[test]
    fn report_rows_become_hotspots_in_order() {
        assert_eq!(
            hotspots(REPORT),
            vec![
                Hotspot {
                    overhead: String::from("42.77%"),
                    dso: String::from("libc.so.6"),
                    symbol: String::from("[.] splice")
                },
                Hotspot {
                    overhead: String::from("35.22%"),
                    dso: String::from("yes"),
                    symbol: String::from("[.] drop_in_place<Vec<u8> >")
                },
            ]
        );
    }

    #[test]
    fn sample_count_is_read_from_the_header() {
        assert_eq!(samples(REPORT), "159");
    }

    #[test]
    fn rendering_names_when_and_what_and_escapes_pipes() {
        let hot: Vec<Hotspot> = vec![Hotspot {
            overhead: String::from("1.00%"),
            dso: String::from("a"),
            symbol: String::from("[.] f|g"),
        }];
        assert_eq!(
            render("2026-11-09T00:00:00Z", 7, "yes y", 2, "8", &hot),
            "# Hot path\n\nGenerated by `cargo xtask profile` at 2026-11-09T00:00:00Z from `perf record -g -e task-clock` on pid 7 (`yes y`) for 2 s, 8 samples. Self time, top 25 symbols.\n\n| Self | DSO | Symbol |\n|---:|---|---|\n| 1.00% | a | `[.] f\\|g` |\n"
        );
    }
}
